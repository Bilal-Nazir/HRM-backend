import { Router } from "express";
import { authMiddleware, requireOrganization } from "../../AuthModule/utils/authMiddleware";
import { asyncWrapper } from "../../node-base/utils";
import * as controller from "../controllers/ProjectController";

const router = Router();
router.use(authMiddleware(), requireOrganization);
router.get("/my-tasks", asyncWrapper(controller.myTasks));
router.get("/dashboard", asyncWrapper(controller.dashboardSummary));
router.get("/", asyncWrapper(controller.listProjects));
router.post("/", asyncWrapper(controller.createProject));
router.get("/:id", asyncWrapper(controller.getProject));
router.patch("/:id", asyncWrapper(controller.updateProject));
router.patch("/:id/archive", asyncWrapper(controller.archiveProject));
router.get("/:id/overview", asyncWrapper(controller.overview));
router.get("/:id/members", asyncWrapper(controller.listMembers));
router.post("/:id/members", asyncWrapper(controller.addMembers));
router.patch("/:id/members/:employeeId", asyncWrapper(controller.updateMember));
router.delete("/:id/members/:employeeId", asyncWrapper(controller.removeMember));
router.get("/:id/workflow", asyncWrapper(controller.getWorkflow));
router.post("/:id/workflow/statuses", asyncWrapper(controller.createStatus));
router.patch("/:id/workflow/statuses/reorder", asyncWrapper(controller.reorderStatuses));
router.patch("/:id/workflow/statuses/:statusId", asyncWrapper(controller.updateStatus));
router.delete("/:id/workflow/statuses/:statusId", asyncWrapper(controller.deleteStatus));
router.get("/:id/tasks", asyncWrapper(controller.listTasks));
router.post("/:id/tasks", asyncWrapper(controller.createTask));
router.get("/:id/tasks/:taskId", asyncWrapper(controller.getTask));
router.patch("/:id/tasks/:taskId", asyncWrapper(controller.updateTask));
router.patch("/:id/tasks/:taskId/status", asyncWrapper(controller.moveTask));
router.post("/:id/tasks/:taskId/comments", asyncWrapper(controller.addComment));
router.post("/:id/tasks/:taskId/attachments", asyncWrapper(controller.addAttachment));
router.get("/:id/attachments/:attachmentId", asyncWrapper(controller.downloadAttachment));
router.get("/:id/activity", asyncWrapper(controller.listActivity));
export default router;
